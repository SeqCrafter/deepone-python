import hashlib
import json
from importlib.resources import files
from pathlib import Path

import numpy as np
import pytest

from DeepOneCalculator import SUPPORTED_CELL_LINES, calculate_deepone
from DeepOneCalculator.features import _encode, _energy
from DeepOneCalculator.inference import _predict
from DeepOneCalculator.resources import _manifest

TARGETS = ["AAAA" + "ATATATATATATATATATAT" + "AGG" + "AAA",
           "TTATCTTCGCTATCACCTCCGCCGGGGTCACCCATTAT"]


def test_packaged_weights() -> None:
    assert set(_manifest()) == {*SUPPORTED_CELL_LINES, "SpCas9-NG", "SpG"}
    for cell_line in _manifest():
        assert len(_manifest()[cell_line]) == 5
        for entry in _manifest()[cell_line]:
            resource = files("DeepOneCalculator").joinpath("models").joinpath(entry["file"])
            data = resource.read_bytes()
            assert len(data) < 5_000_000
            assert hashlib.sha256(data).hexdigest() == entry["sha256"]


@pytest.mark.integration
def test_real_ensembles() -> None:
    scores = calculate_deepone(TARGETS, "all", batch_size=2, device="cpu")
    assert set(scores.cell_line) == set(SUPPORTED_CELL_LINES)
    assert scores.groupby("cell_line").size().nunique() == 1
    assert set(scores.sequence_id) == {"sequence_1", "sequence_2"}
    assert np.isfinite(scores.deepone_score).all()
    repeated = calculate_deepone(TARGETS, "K562", batch_size=1, device="cpu")
    np.testing.assert_allclose(scores.loc[scores.cell_line == "K562", "deepone_score"],
                               repeated.deepone_score, rtol=1e-5, atol=1e-5)


@pytest.mark.integration
def test_original_architecture_reference() -> None:
    # Reference generated by unmodified utils/DL_model.py with the same corrected
    # energy inputs; catches changes to channel, flatten, focus or weight ordering.
    reference = json.loads(Path(__file__).with_name("model_reference.json").read_text())
    contexts = reference["contexts"]
    encoded = _encode(contexts)
    energies = np.array([[_energy(s[4:27])] for s in contexts], dtype=np.float32)
    for cell_line, expected in reference["scores"].items():
        actual = _predict(encoded, energies, cell_line, "/CPU:0", 1)
        np.testing.assert_allclose(actual, expected, rtol=1e-5, atol=1e-5)
